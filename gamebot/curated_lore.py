def get_all_curated_franchises() -> List[str]:
    """Returns a deduplicated list of all franchises present in the curated catalog."""
    seen = set()
    result = []
    for entry in CURATED_POSTS:
        if entry.franchise not in seen:
            seen.add(entry.franchise)
            result.append(entry.franchise)
    return result


def get_curated_post_for_franchise(
    franchise: str,
    excluded_topics: Optional[List[str]] = None,
) -> Optional[CuratedLoreEntry]:
    """
    Finds a curated post for a specific franchise, skipping topics in excluded_topics.
    If all topics for this franchise are excluded, returns the oldest or first available.
    """
    clean_target = franchise.strip().lower()
    excluded = {str(t).strip().lower() for t in (excluded_topics or [])}

    matching = [
        p for p in CURATED_POSTS
        if clean_target in p.franchise.lower() or p.franchise.lower() in clean_target
    ]
    if not matching:
        return None

    # Filter out excluded topics
    available = [
        p for p in matching
        if p.topic_key.lower() not in excluded and p.topic_title.lower() not in excluded
    ]
    if available:
        return random.choice(available)

    # If all matching posts are in excluded_topics, return any matching
    return matching[0]


def get_any_unexcluded_curated_post(
    excluded_topics: Optional[List[str]] = None,
) -> CuratedLoreEntry:
    """
    Returns an unexcluded curated post from any franchise.
    Guaranteed to return a valid CuratedLoreEntry.
    """
    excluded = {str(t).strip().lower() for t in (excluded_topics or [])}
    available = [
        p for p in CURATED_POSTS
        if p.topic_key.lower() not in excluded and p.topic_title.lower() not in excluded
    ]
    if available:
        return random.choice(available)
    return random.choice(CURATED_POSTS)
